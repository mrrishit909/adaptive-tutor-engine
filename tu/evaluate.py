"""Offline evaluation with simulated students. Writes docs/evaluation.md.

    python -m tu.evaluate
"""
import pathlib
import random
import statistics

from . import curriculum as cu
from . import engine, world

N = 400


def auc(y, p):
    pairs = sorted(zip(p, y))
    rank_sum, pos = 0.0, sum(y)
    i = 0
    while i < len(pairs):
        j = i
        while j < len(pairs) and pairs[j][0] == pairs[i][0]:
            j += 1
        rank_sum += sum(y_ for _, y_ in pairs[i:j]) * (i + j + 1) / 2
        i = j
    return (rank_sum - pos * (pos + 1) / 2) / (pos * (len(y) - pos))


def diagnosis(n=600, seed=5):
    """After the placement quiz plus 12 tutor-chosen activities: which misconceptions does the tutor suspect, against which are held?"""
    tp = fp = fn = btp = bfp = 0
    for s in range(n):
        rng = random.Random(f"diag-{seed}-{s}")
        st, state, wrong_on = world.student(rng), engine.new_state(), set()
        for k in cu.KEYS:
            item = cu.generate(k, rng, target=(cu.EXPOSES[k] or [None])[0])
            resp = world.respond(st, item, rng)
            engine.update(state, item, resp, 0)
            if resp != item["answer"]:
                wrong_on.update(cu.EXPOSES[k])
        held = set(st["holds"])                                 # as they stood when the quiz was taken
        flagged = {m for m in cu.MISCONCEPTIONS if state["m"][m] >= engine.SUSPECT}
        tp, fp, fn = tp + len(flagged & held), fp + len(flagged - held), fn + len(held - flagged)
        btp, bfp = btp + len(wrong_on & held), bfp + len(wrong_on - held)
    return {"precision": tp / max(1, tp + fp), "recall": tp / max(1, tp + fn), "base_precision": btp / max(1, btp + bfp), "base_recall": btp / max(1, tp + fn), "held": tp + fn}


def main():
    log, learnt = [], {}
    arms = {"adaptive": world.run("adaptive", N, bandit=learnt, log=log), "practice_only": world.run("adaptive", N, bandit={(s, c): [10**6 * (s == "practice"), 10**6] for s in engine.STRATEGIES for c in ("new", "practised")}),
            "fixed": world.run("fixed", N)}
    m = lambda arm, k: statistics.mean(r[k] for r in arms[arm])      # noqa: E731
    diff = [a["after"] - f["after"] for a, f in zip(arms["adaptive"], arms["fixed"])]
    se = statistics.stdev(diff) / len(diff) ** 0.5
    y, p = [int(c) for _, _, c in log], [g for _, g, _ in log]
    running, seen = [], {}
    for s, _, c in log:
        k, n = seen.get(s, (0, 0))
        running.append((k + 1) / (n + 2))
        seen[s] = (k + c, n + 1)
    bins = [(0, 0.2), (0.2, 0.4), (0.4, 0.6), (0.6, 0.8), (0.8, 1.01)]
    d = diagnosis()
    gap = statistics.mean(abs(r["believed"] - r["after"]) for r in arms["adaptive"])
    best = {c: max(engine.STRATEGIES, key=lambda s: world.BOOST[s, c]) for c in ("new", "practised")}
    lines = ["# Evaluation", "",
             f"Generated by `python -m tu.evaluate` with {N} simulated students per arm, 30 days, 4 activities a day, 18 concepts.",
             "**The students are simulated.** They learn, slip, hold misconceptions and forget according to a model of the same family the tutor assumes (with different numbers: for example they learn faster and forget faster than the tutor thinks).",
             "So this shows the tutor does what it is designed to do in that world. It is not evidence about real learners.", "",
             "## 1. Adaptive against a fixed sequence", "",
             "The same students are taught three ways. The control is every concept in course order, five new items each, with a mixed review every fourth activity.", "",
             "| | Concepts mastered at the end | Two weeks later, no practice | Misconceptions still held |", "|---|---|---|---|",
             f"| Adaptive tutor | {m('adaptive', 'after'):.2f} | {m('adaptive', 'later'):.2f} | {m('adaptive', 'misconceptions_left'):.2f} |",
             f"| Adaptive, but always plain practice (no strategy choice) | {m('practice_only', 'after'):.2f} | {m('practice_only', 'later'):.2f} | {m('practice_only', 'misconceptions_left'):.2f} |",
             f"| Fixed sequence with review | {m('fixed', 'after'):.2f} | {m('fixed', 'later'):.2f} | {m('fixed', 'misconceptions_left'):.2f} |", "",
             f"Students started with {m('adaptive', 'before'):.2f} concepts mastered on average. Adaptive minus fixed: {statistics.mean(diff):.2f} concepts (95% interval {statistics.mean(diff) - 1.96 * se:.2f} to {statistics.mean(diff) + 1.96 * se:.2f});",
             f"{sum(x > 0 for x in diff)} of {N} students ended ahead, {sum(x < 0 for x in diff)} behind.",
             f"Most of the gap is the misconceptions: in this simulator a held misconception blocks every concept that depends on it, the fixed sequence never targets one, and so it leaves {m('fixed', 'misconceptions_left'):.2f} of them in place per student.", "",
             "## 2. Does the tutor know what the student knows?", "",
             f"Before each of the {len(y):,} answers in the adaptive arm the tutor's estimate of a correct answer was logged.", "",
             "| | AUC |", "|---|---|", f"| Tutor's estimate (mastery x recall) | {auc(y, p):.3f} |", f"| Baseline: the student's running share of correct answers | {auc(y, running):.3f} |", "",
             "| Estimated chance correct | Answers | Mean estimate | Actually correct |", "|---|---|---|---|"]
    for lo, hi in bins:
        k = [i for i, g in enumerate(p) if lo <= g < hi]
        if k:
            lines.append(f"| {lo:.0%} to {min(hi, 1):.0%} | {len(k):,} | {statistics.mean(p[i] for i in k):.1%} | {statistics.mean(y[i] for i in k):.1%} |")
    lines += ["", f"At the end the tutor's count of mastered concepts was off by {gap:.2f} per student on average (out of 18).",
              "The estimates are not well calibrated in the middle of the range: the tutor's learning and forgetting rates are assumed, not fitted to these students.", "",
              "## 3. Spotting misconceptions", "",
              f"600 new students take the 18-item placement quiz. {d['held']} misconceptions are held among them.", "",
              "| | Precision | Recall |", "|---|---|---|", f"| Wrong answer equals what the misconception would give (Bayesian update, flag at {engine.SUSPECT:.0%}) | {d['precision']:.3f} | {d['recall']:.3f} |",
              f"| Baseline: any wrong answer on a concept that exposes it | {d['base_precision']:.3f} | {d['base_recall']:.3f} |", "",
              "The baseline cannot tell a misconception from not having learnt the concept yet.", "",
              "## 4. Choosing how to present an activity", "",
              "The tutor does not know which presentation works best; it learns from whether the next answer on that concept is right (Thompson sampling).", "",
              "| Concept is | Truly best in the simulator | Tutor's most-used | Share of its choices |", "|---|---|---|---|"]
    for c in ("new", "practised"):
        tries = {s: learnt.get((s, c), [0, 0])[1] for s in engine.STRATEGIES}
        top = max(tries, key=tries.get)
        lines.append(f"| {dict(new="new to the learner", practised="already practised")[c]} | {best[c].replace('_', ' ')} | {top.replace('_', ' ')} | {tries[top] / max(1, sum(tries.values())):.0%} |")
    out = pathlib.Path(__file__).resolve().parent.parent / "docs" / "evaluation.md"
    out.write_text("\n".join(lines) + "\n")
    print(out.read_text())


if __name__ == "__main__":
    main()
